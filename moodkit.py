TIER_HINT = {
    "low": "低电量模式 · 每条都是低成本动作",
    "mid": "平稳期 · 小甜头保鲜",
    "good": "有余力 · 存点愉悦储备",
    "empty": "初次见面 · 从一件小事开始",
}


def prescription(avg_score: float | None, latest_risk: str = "L0",
                 seed: int | None = None) -> dict:
    """根据最近情绪状态生成一份心情处方。

    avg_score: 近 30 天平均情绪分（0-100），无记录时传 None
    latest_risk: 最近一次风险等级；L3 时不提供消遣（危机优先）
    """
    if latest_risk == "L3":
        return {
            "mode": "crisis",
            "intro": "现在可能不是玩游戏的时候。比起转移注意力，你更需要一个真实的人——暖光页面里有 24 小时能打通的电话，先花一分钟，联系其中一个。",
            "items": [],
            "hint": "先照顾安全，补给随时都在",
        }

    if avg_score is None:
        tier = "empty"
    elif avg_score < 45:
        tier = "low"
    elif avg_score < 70:
        tier = "mid"
    else:
        tier = "good"

    rng = random.Random(seed) if seed is not None else random.Random()
    # 低电量时给更省力的组合（effort 优先小），状态好时可以上点"奢侈"项
    walks = rng.sample(WALKS, 3)
    eats = rng.sample(EATS, 3)
    if tier in ("low", "empty"):
        dos_pool = [d for d in DOS if d["effort"] == 1]
        walks = [w for w in WALKS if w["effort"] == 1][:6] or walks
        eats = [e for e in EATS if e["effort"] == 1][:6] or eats
        walks = rng.sample(walks, 2)
        eats = rng.sample(eats, 2)
        dos = rng.sample(dos_pool, 2)
    else:
        dos = rng.sample(DOS, 3)
    games = rng.sample(GAMES, 2)

    return {
        "mode": "normal",
        "tier": tier,
        "hint": TIER_HINT[tier],
        "intro": INTROS[tier],
        "walks": walks, "eats": eats, "dos": dos, "games": games,
        "source": "行为激活（Behavioral Activation）——低落时先安排小而具体的活动，情绪跟着行动走",
    }
