def retrieve(query: str, emotion_label: str, top_k: int = 2) -> list[dict]:
    """极简向量化检索：字符 bigram + 关键词命中 + 情绪标签匹配。"""
    def grams(s: str) -> set[str]:
        s = "".join(ch for ch in s if ch.strip())
        return {s[i:i + 2] for i in range(len(s) - 1)} | set(s)

    q = grams(query)
    scored: list[tuple[float, dict]] = []
    for kb in KNOWLEDGE_BASE:
        kw_hit = sum(1 for t in kb["triggers"] if t in query)
        corpus = grams(kb["topic"] + kb["content"] + "".join(kb["triggers"]))
        overlap = len(q & corpus) / (len(q) + 6)
        tag_bonus = 0.35 if emotion_label in kb["tags"] else 0.0
        score = kw_hit * 0.55 + overlap * 1.6 + tag_bonus
        if kw_hit == 0:
            score *= 0.35       # 没有直接关键词就大幅降权，避免"编"
        scored.append((score, kb))

    scored.sort(key=lambda x: x[0], reverse=True)
    # 提高门槛：宁可说"我不确定"，也不硬套一张不相关的知识卡
    hits = [(s, kb) for s, kb in scored if s >= 0.78 and kb["tags"] and emotion_label in kb["tags"]][:top_k]
    if not hits:
        hits = [(s, kb) for s, kb in scored if s >= 0.95][:1]
    return [{"score": round(s, 3), **kb} for s, kb in hits]


